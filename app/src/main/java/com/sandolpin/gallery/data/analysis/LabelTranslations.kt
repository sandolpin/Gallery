    /** 日本語の名前の表を、ML Kit の英語名から引く。キーは、大文字小文字を区別しない。 */
    private val tableByLowercase: Map<String, List<String>> =
        table.mapKeys { it.key.lowercase(Locale.ROOT) }

    /** 表示用の名前。表にないラベルは、英語のまま返す。 */
    fun displayName(label: String): String =
        tableByLowercase[label.lowercase(Locale.ROOT)]?.firstOrNull() ?: label

    /**
     * 検索の言葉([query])に、あてはまる英語のラベルを、すべて返す(8-Dの検索で使う)。
     * - 日本語の名前が、検索の言葉と同じなら、あてはまる。2文字以上の言葉は、名前の一部に含まれていても、あてはまる(部分一致)。
     *   (1文字の言葉は、同じ名前だけにする。「海」で「海老」(エビ)が混ざらないようにするため)
     *   英語の名前でも、同じ。
     * - 全角・半角、英字の大文字小文字は区別しない(NFKC)。ひらがなとカタカナは、区別する。
     * 空の言葉には、空の集合を返す。
     */
    fun labelsMatching(query: String): Set<String> {
        val needle = normalize(query)
        if (needle.isEmpty()) return emptySet()
        fun matches(name: String): Boolean {
            val normalized = normalize(name)
            return normalized == needle || (needle.length >= 2 && normalized.contains(needle))
        }
        return table.entries
            .filter { (english, japanese) -> matches(english) || japanese.any(::matches) }
            .mapTo(LinkedHashSet()) { it.key }
    }

    private fun normalize(text: String): String =
        Normalizer.normalize(text, Normalizer.Form.NFKC).lowercase(Locale.ROOT).trim()
